// Command generate renders the libdns provider registry and its documentation
// from the single source providers.json.
//
// Usage: go run ./internal/generator/generate.go <providers.json> <registry.go> <PROVIDERS.md>
package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"go/types"
	"os"
	"os/exec"
	"reflect"
	"slices"
	"strconv"
	"strings"
	"text/template"
)

const (
	providerTypeName = "Provider"
	fileMode         = 0o644

	registryTemplate = `// Code generated by internal/generator from providers.json. DO NOT EDIT.

package libdnsregistry

import (
	{{- range .}}
	libdns{{.Name}} "{{.Package}}"
	{{- end}}
)

var registry = RegistryStore{
	{{- range .}}
	"{{.Name}}": &RegistryProvider{
		Init: func(conf [][]byte) (Provider, error) {
			return initProvider[libdns{{.Name}}.Provider](conf)
		},
	},
	{{- end}}
}
`

	docsTemplate = `<!-- Code generated by internal/generator from providers.json. DO NOT EDIT. -->

# Supported providers

Select a provider with ` + "`LIBDNS_PROVIDER_NAME`" + ` and pass its configuration as JSON via ` + "`LIBDNS_PROVIDER_CONFIG`" + `.

| Name | Description |
| --- | --- |
{{- range .}}
| [{{.Name}}](#{{.Name}}) | {{cell .Description}} |
{{- end}}
{{range .}}
## {{.Name}}

{{if .URL}}[{{.URL}}]({{.URL}}) · {{end}}[{{.Package}}](https://pkg.go.dev/{{.Package}})
{{- if .Description}}

{{.Description}}
{{- end}}

{{if .Fields -}}
| Key | Type | Description |
| --- | --- | --- |
{{- range .Fields}}
| ` + "`{{.Key}}`" + ` | ` + "`{{.Type}}`" + ` | {{cell .Doc}} |
{{- end}}

` + "```sh" + `
LIBDNS_PROVIDER_NAME={{.Name}}
LIBDNS_PROVIDER_CONFIG='{{.Example}}'
` + "```" + `
{{- else -}}
No configuration fields found.
{{- end}}
{{end -}}
`
)

type providerSource struct {
	Name        string `json:"name"`
	Package     string `json:"package"`
	Description string `json:"description,omitempty"`
	URL         string `json:"url,omitempty"`
}

type configField struct {
	Key  string
	Type string
	Doc  string
}

type providerDoc struct {
	providerSource

	Fields  []configField
	Example string
}

func main() {
	if err := run(os.Args[1:]); err != nil {
		fmt.Fprintln(os.Stderr, "generate:", err)
		os.Exit(1)
	}
}

func run(args []string) error {
	if len(args) != 3 {
		return errors.New("usage: generate <providers.json> <registry.go> <PROVIDERS.md>")
	}

	providers, err := readProviders(args[0])
	if err != nil {
		return err
	}

	if err := generateRegistry(args[1], providers); err != nil {
		return err
	}

	return generateDocs(args[2], providers)
}

func readProviders(path string) ([]providerSource, error) {
	listJSON, err := os.ReadFile(path) //nolint:gosec // path is provided by go:generate
	if err != nil {
		return nil, fmt.Errorf("read provider list: %w", err)
	}

	var providers []providerSource
	if err := json.Unmarshal(listJSON, &providers); err != nil {
		return nil, fmt.Errorf("decode provider list: %w", err)
	}

	slices.SortFunc(providers, func(a, b providerSource) int { return strings.Compare(a.Name, b.Name) })

	return providers, nil
}

func generateRegistry(path string, providers []providerSource) error {
	tpl := template.Must(template.New("registry").Parse(registryTemplate))

	content := &bytes.Buffer{}
	if err := tpl.Execute(content, providers); err != nil {
		return fmt.Errorf("render registry: %w", err)
	}

	formatted, err := format.Source(content.Bytes())
	if err != nil {
		return fmt.Errorf("format registry: %w", err)
	}

	return writeFile(path, formatted)
}

func generateDocs(path string, providers []providerSource) error {
	files, err := packageFiles(providers)
	if err != nil {
		return err
	}

	docs := make([]providerDoc, 0, len(providers))

	for _, provider := range providers {
		fields, err := providerFields(files[provider.Package])
		if err != nil {
			return fmt.Errorf("provider %s: %w", provider.Name, err)
		}

		docs = append(docs, providerDoc{
			providerSource: provider,
			Fields:         fields,
			Example:        exampleConfig(fields),
		})
	}

	tpl := template.Must(template.New("docs").Funcs(template.FuncMap{"cell": tableCell}).Parse(docsTemplate))

	content := &bytes.Buffer{}
	if err := tpl.Execute(content, docs); err != nil {
		return fmt.Errorf("render docs: %w", err)
	}

	return writeFile(path, content.Bytes())
}

func writeFile(path string, content []byte) error {
	if err := os.WriteFile(path, content, fileMode); err != nil { //nolint:gosec // path is provided by go:generate
		return fmt.Errorf("write %s: %w", path, err)
	}

	return nil
}

// packageFiles resolves the Go source files of every provider package from the module cache.
func packageFiles(providers []providerSource) (map[string][]string, error) {
	args := make([]string, 0, len(providers)+3) //nolint:mnd // go list flags
	args = append(args, "list", "-f", `{{.ImportPath}} {{range .GoFiles}}{{$.Dir}}/{{.}} {{end}}`)

	for _, provider := range providers {
		args = append(args, provider.Package)
	}

	out, err := exec.Command("go", args...).Output() //nolint:noctx // fixed binary, package list from providers.json
	if err != nil {
		return nil, fmt.Errorf("go list provider packages: %w", err)
	}

	files := map[string][]string{}

	for line := range strings.Lines(string(out)) {
		if fields := strings.Fields(line); len(fields) > 1 {
			files[fields[0]] = fields[1:]
		}
	}

	return files, nil
}

// providerFields extracts the JSON configurable fields of the Provider struct within the package files.
func providerFields(files []string) ([]configField, error) {
	if len(files) == 0 {
		return nil, errors.New("package source not found, run go mod download")
	}

	fset := token.NewFileSet()
	structs := map[string]*ast.StructType{}

	for _, path := range files {
		file, err := parser.ParseFile(fset, path, nil, parser.ParseComments)
		if err != nil {
			return nil, fmt.Errorf("parse %s: %w", path, err)
		}

		for _, decl := range file.Decls {
			gen, ok := decl.(*ast.GenDecl)
			if !ok || gen.Tok != token.TYPE {
				continue
			}

			for _, spec := range gen.Specs {
				typeSpec, _ := spec.(*ast.TypeSpec)
				if st, ok := typeSpec.Type.(*ast.StructType); ok {
					structs[typeSpec.Name.Name] = st
				}
			}
		}
	}

	provider, ok := structs[providerTypeName]
	if !ok {
		return nil, errors.New("type Provider struct not found")
	}

	return structFields(provider, structs, map[string]bool{providerTypeName: true}), nil
}

// structFields follows encoding/json rules: exported fields, json tag names, "-" skipped and
// untagged embedded structs of the same package flattened.
func structFields(st *ast.StructType, structs map[string]*ast.StructType, seen map[string]bool) []configField {
	var fields []configField

	for _, field := range st.Fields.List {
		key, skip := jsonKey(field)
		if skip {
			continue
		}

		if len(field.Names) == 0 {
			embedded := embeddedName(field.Type)
			if embedded == "" || !ast.IsExported(embedded) {
				continue
			}

			if nested, ok := structs[embedded]; ok && key == "" && !seen[embedded] {
				seen[embedded] = true
				fields = append(fields, structFields(nested, structs, seen)...)

				continue
			}

			fields = append(fields, newConfigField(field, key, embedded))

			continue
		}

		for _, name := range field.Names {
			if name.IsExported() {
				fields = append(fields, newConfigField(field, key, name.Name))
			}
		}
	}

	return fields
}

func newConfigField(field *ast.Field, key, name string) configField {
	if key == "" {
		key = name
	}

	doc := field.Doc.Text()
	if doc == "" {
		doc = field.Comment.Text()
	}

	return configField{
		Key:  key,
		Type: types.ExprString(field.Type),
		Doc:  strings.Join(strings.Fields(doc), " "),
	}
}

func jsonKey(field *ast.Field) (string, bool) {
	if field.Tag == nil {
		return "", false
	}

	tag, err := strconv.Unquote(field.Tag.Value)
	if err != nil {
		return "", false
	}

	name, _, _ := strings.Cut(reflect.StructTag(tag).Get("json"), ",")

	return name, name == "-"
}

func embeddedName(expr ast.Expr) string {
	switch typ := expr.(type) {
	case *ast.Ident:
		return typ.Name
	case *ast.StarExpr:
		return embeddedName(typ.X)
	case *ast.SelectorExpr:
		return typ.Sel.Name
	default:
		return ""
	}
}

func exampleConfig(fields []configField) string {
	example := map[string]any{}

	for _, field := range fields {
		switch field.Type {
		case "bool":
			example[field.Key] = false
		case "int", "int8", "int16", "int32", "int64", "uint", "uint8", "uint16", "uint32", "uint64", "float32", "float64":
			example[field.Key] = 0
		case "string":
			example[field.Key] = ""
		default:
			example[field.Key] = nil
		}
	}

	out, _ := json.Marshal(example) //nolint:errchkjson // map of plain values

	return string(out)
}

func tableCell(text string) string {
	return strings.ReplaceAll(strings.Join(strings.Fields(text), " "), "|", `\|`)
}
